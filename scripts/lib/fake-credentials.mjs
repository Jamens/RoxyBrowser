/**
 * 测试用的**假凭据**生成器 —— 全仓唯一的出处。
 *
 * ## 为什么需要这个模块
 *
 * 本项目的硬约束：**仓库里不得出现任何真实或形似真实的密钥**。
 *
 * 验证脚本（云端 BYOK 链路、设置页保存可见性）都需要往代码里传一个
 * 「像密钥的值」才能触发对应的分支：比如前端判定「这看起来是 API Key」靠的是
 * **前缀匹配**（`/^(sk-|sk_ant-|AIza|gsk_|xai-|hf_|r8_|dop_v1_)/i`），
 * mock 服务要识别「无效 Key」靠的是 Authorization 头的**精确比对**。
 *
 * 若把这些值写成源码字面量，会带来三个实际风险：
 *
 * 1. **密钥扫描器误报** —— CI / 提交钩子里的 secret scanner 按
 *    「前缀 + 长度」匹配，`sk-` 后面跟一串十六进制会被判成真实凭据并拦截。
 *    告警多了大家就学会忽略，告警随即失去意义。
 * 2. **真实凭据的滑坡入口** —— 源码里已经躺着一个「格式完全正确的 key」时，
 *    下一个人顺手把测试值换成自己真实 Key 去「验证一下」几乎零阻力。
 *    这正是凭据泄漏最常见的路径。
 * 3. **散落各处、难以审计** —— 每个脚本各写一个，改起来要翻遍全仓，
 *    也无从保证「所有测试凭据都从同一个受控来源来」。
 *
 * 故统一改为**运行时拼装**：源码里只有前缀片段与占位字符，
 * 任何静态扫描（正则 / grep / secret scanner）都扫不出完整密钥形态。
 *
 * ## 语义等价性（重要）
 *
 * 拼装值与手写字面量在**被测行为上完全一致**：
 * - 前端的密钥识别是**前缀匹配** → 只要前缀对，判定结果不变；
 * - mock 的无效 Key 识别是**精确比对** → mock 与调用方都从本模块取同一个值，
 *   比对照样成立。
 *
 * 故这不是「换个凑合的值」，而是把同一个值换了个**不落盘**的产生方式。
 */

/** 前缀片段（单独存放，避免任何一处出现完整密钥形态） */
const PREFIX_SK = 'sk-'

/**
 * 通用假 Key：用于「需要被识别成密钥」的场景（如验证地址栏误填的拦截）。
 *
 * 主体用 `x` 填充而非十六进制——十六进制形态更接近真实凭据，
 * 而这里只需要「长度足够、不触发厂商特征误判」即可。
 */
export function fakeKey(bodyLength = 32) {
  return PREFIX_SK + 'x'.repeat(bodyLength)
}

/**
 * 假 Key 的**哨兵变体**：给不同用途一个可区分的名字，
 * 便于日志里看出「这次测的是哪条分支」，同时依然由前缀拼装而来。
 *
 * @param tag 用途标记（如 'test' / 'invalid' / 'ping'）
 */
export function fakeKeyWithTag(tag) {
  return PREFIX_SK + tag + '-' + 'x'.repeat(8)
}

/** mock 服务用「无效 Key」的精确值（调用方与 mock 必须取同一个） */
export const INVALID_KEY = fakeKeyWithTag('invalid')
